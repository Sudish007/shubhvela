// Generates data/verified-dates.json (plan A12, F23 footer): for every festival slug-year-tradition whose engine
// date equals the date Drik Panchang printed for the reference city of that tradition (Delhi = Purnimanta, Chennai =
// Amanta; reference/festivals/drikpanchang/<city>-<year>.json fetched by A04), one entry carrying the Drik page's
// fetch date. The app's festival detail shows "verified against Drik Panchang on <date>" ONLY when its own computed
// date equals the verified one; every other festival-year honestly reads "not yet verified". Nothing here is typed by
// hand: dates come from the engine and the fetched pages, the comparison is the same as test/suites/festivals.
// Run with: npx tsx packages/engine/scripts/build-verified-dates.ts   (or npm run build:verified -w packages/engine)
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { festivals } from '../src/calendar/festivals';
import { normName } from '../test/suites/_shared';

const HERE = dirname(fileURLToPath(import.meta.url));
const REFERENCE = join(HERE, '..', 'reference', 'festivals');
const OUT = join(HERE, '..', 'data', 'verified-dates.json');

interface City {
  geonameId: number;
  name: string;
  lat: number;
  lon: number;
  tz: string;
  tradition: 'purnimanta' | 'amanta';
  region: 'north' | 'south';
}
interface Cases {
  years: number[];
  cities: Record<string, City>;
  slugs: string[];
}
interface DrikEvent {
  name: string;
  date: string;
  text: string;
}
interface NameMap {
  map: Record<string, { names: string[]; textFilter?: string }>;
}
interface RefFile {
  source: string;
  source_url: string;
  fetched_at: string;
  values: { events: DrikEvent[] };
}

export interface VerifiedEntry {
  /** Engine date that matched the reference (YYYY-MM-DD, at the reference city). */
  date: string;
  /** Fetch date of the Drik page (YYYY-MM-DD). */
  fetchedAt: string;
  city: string;
  source: 'drikpanchang';
}
export interface VerifiedDates {
  generatedAt: string;
  description: string;
  entries: Record<string, VerifiedEntry>;
}

function read<T>(p: string): T {
  return JSON.parse(readFileSync(p, 'utf8').replace(/^\uFEFF/, '')) as T;
}

const cases = read<Cases>(join(REFERENCE, 'cases.json'));
const nameMap = read<NameMap>(join(REFERENCE, 'name-map.json'));
const entries: Record<string, VerifiedEntry> = {};
let compared = 0;

for (const [cityId, city] of Object.entries(cases.cities)) {
  for (const year of cases.years) {
    const file = join(REFERENCE, 'drikpanchang', `${cityId}-${year}.json`);
    if (!existsSync(file)) continue;
    const ref = read<RefFile>(file);
    const fetchedAt = ref.fetched_at.slice(0, 10);
    const geo = { lat: city.lat, lon: city.lon };
    const engineAll = [...festivals(year, city.tradition, 'north', geo, city.tz), ...festivals(year, city.tradition, 'south', geo, city.tz)];
    for (const slug of cases.slugs) {
      const spec = nameMap.map[slug];
      if (!spec) continue;
      const wanted = spec.names.map(normName);
      const filter = spec.textFilter ? new RegExp(spec.textFilter, 'i') : null;
      const drik = [...new Set(ref.values.events.filter((e) => wanted.includes(normName(e.name)) && (!filter || filter.test(e.text))).map((e) => e.date))].sort();
      if (!drik.length) continue;
      const engine = [...new Set(engineAll.filter((f) => f.slug === slug && (f.day === undefined || f.day === 1)).map((f) => f.date))].sort();
      compared++;
      if (engine.length === drik.length && engine.every((d, i) => d === drik[i])) {
        for (const date of engine) entries[`${slug}|${year}|${city.tradition}|${date}`] = { date, fetchedAt, city: cityId, source: 'drikpanchang' };
      }
    }
  }
}

const out: VerifiedDates = {
  generatedAt: new Date().toISOString(),
  description:
    'Festival dates whose engine value equals the date printed by Drik Panchang for the reference city of the tradition (Delhi = Purnimanta, Chennai = Amanta). Key = slug|year|tradition|date. Generated by scripts/build-verified-dates.ts from reference/festivals; the app shows "verified against Drik Panchang on <fetchedAt>" only when its computed date equals `date`, else "not yet verified".',
  entries,
};
writeFileSync(OUT, JSON.stringify(out, null, 2) + '\n', 'utf8');
// eslint-disable-next-line no-console
console.log(`verified-dates.json: ${Object.keys(entries).length} verified slug-year-tradition dates out of ${compared} compared -> ${OUT}`);
